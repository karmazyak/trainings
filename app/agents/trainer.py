        "Для новичков — более подробно. Для продвинутых — кратко, только нюансы.\n"
        "Если в базе знаний есть описание техники — используй именно его.\n\n"
        "БАЗОВЫЕ ПОКАЗАТЕЛИ ПОЛЬЗОВАТЕЛЯ:\n"
