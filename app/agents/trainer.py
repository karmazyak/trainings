        "- Бег: лёгкий бег, интервалы, темпо, длинная тренировка, фартлек.\n"
        "- Включай работу на подвижность, баланс и дыхание.\n"
        "- Прогрессия: увеличивай длительность/сложность асан постепенно.\n"
        "- Дни восстановления: инь-йога или лёгкая растяжка.\n\n"

