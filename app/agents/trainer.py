        "  - Фокус на тяжёлых базовых: 6-10 повторений, прогрессия весов.\n"
        "  - Минимум кардио: 1-2 раза в неделю по 15-20 мин LISS для здоровья сердца.\n"
        "  - Объём повышенный: можно 5-6 упражнений, 16-20 рабочих подходов.\n\n"
        "• Поддержание формы:\n"
        "  - Баланс силовых и кардио (3:2 или 2:2).\n"
        "  - Разнообразие: чередуй типы тренировок, чтобы не скучать.\n\n"
        "• Сила и выносливость:\n"
        "  - Низкие повторения (3-6) с тяжёлыми весами в базовых.\n"
