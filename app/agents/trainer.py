        "• Похудение / сушка:\n"
        "  - ОБЯЗАТЕЛЬНО включай кардио: 20-30 мин после силовой ИЛИ отдельные кардио-дни.\n"
        "  - Рекомендуй LISS (быстрая ходьба, велосипед 120-140 ЧСС) 3-4 раза в неделю.\n"
